//! Python's `repr` of a string.

use std::fmt::Write as _;

/// `text` as Python's `repr` writes a string: single quotes unless only double quotes avoid
/// escaping, and escapes for backslashes, the quote, controls and unprintable characters.
pub(crate) fn repr(text: &str) -> String {
    let quote = if text.contains('\'') && !text.contains('"') {
        '"'
    } else {
        '\''
    };
    let mut out = String::with_capacity(text.len() + 2);
    out.push(quote);
    for ch in text.chars() {
        let code = u32::from(ch);
        match ch {
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if c == quote => {
                out.push('\\');
                out.push(c);
            }
            _ if code < 0x20 || code == 0x7f => {
                let _ = write!(out, "\\x{code:02x}");
            }
            c if c.is_ascii() || printable(c) => out.push(c),
            _ if code <= 0xff => {
                let _ = write!(out, "\\x{code:02x}");
            }
            _ if code <= 0xffff => {
                let _ = write!(out, "\\u{code:04x}");
            }
            _ => {
                let _ = write!(out, "\\U{code:08x}");
            }
        }
    }
    out.push(quote);
    out
}

/// Whether `c`, outside ASCII, is printable for Python's `str.isprintable` in the Unicode
/// version of the reference's interpreter.
fn printable(c: char) -> bool {
    let code = u32::from(c);
    let at = NOT_PRINTABLE.partition_point(|&[_, hi]| hi < code);
    NOT_PRINTABLE.get(at).is_none_or(|&[lo, _]| code < lo)
}

