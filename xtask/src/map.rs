//! `docs/architecture/module-map.md`, generated from `cargo metadata`, `contracts/index.json`
//! and `ecosystem.lock`. Never edited by hand; CI regenerates it and fails on a diff.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

use crate::contracts;
use crate::util::{self, Errors, Res};

pub fn run(root: &Path, check: bool) -> Res {
    let text = render(root).map_err(|e| vec![e])?;
    let mut errors = Errors::new();
    util::write_or_check(
        root,
        &root.join("docs/architecture/module-map.md"),
        &text,
        check,
        &mut errors,
    );
    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors)
    }
}

fn render(root: &Path) -> Result<String, String> {
    let meta = util::metadata(root)?;
    let contracts = contracts::load(root)?;
    let lock: toml::Table = util::read(&root.join("ecosystem.lock"))?
        .parse()
        .map_err(|e| format!("ecosystem.lock: {e}"))?;
    let empty = Vec::new();
    let mut pkgs: Vec<&Value> = meta["packages"]
        .as_array()
        .unwrap_or(&empty)
        .iter()
        .filter(|p| p["name"].as_str() != Some("xtask"))
        .collect();
    pkgs.sort_by_key(|p| p["name"].as_str().unwrap_or("").to_string());

    let mut s = String::new();
    s.push_str("<!-- GENERATED by `cargo xtask module-map` from cargo metadata, contracts/index.json and ecosystem.lock. Do not edit by hand. -->\n\n");
    s.push_str("# Module map\n\nModules talk to each other only through `ulei-contracts` (types generated from `contracts/`) and the wire. Class-1 products live in their own repositories and are pinned in `ecosystem.lock`. Rules: [ADR-0001](adr/0001-cargo-workspace-and-module-classes.md).\n\n");
    s.push_str("## Crates\n\n| Crate | Path | Class | Role | Contracts | Workspace deps | External deps |\n|---|---|---|---|---|---|---|\n");
    let mut edges = Vec::new();
    for p in &pkgs {
        let name = p["name"].as_str().unwrap_or("?");
        let path = util::rel(root, Path::new(p["manifest_path"].as_str().unwrap_or("")));
        let path = path.trim_end_matches("/Cargo.toml");
        let ulei = &p["metadata"]["ulei"];
        let class = match &ulei["class"] {
            Value::String(s) => s.clone(),
            v => v.to_string(),
        };
        let used: Vec<&str> = ulei["contracts"]
            .as_array()
            .map(|a| a.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let deps = p["dependencies"].as_array().unwrap_or(&empty);
        let mut ws: Vec<&str> = deps
            .iter()
            .filter(|d| d["path"].is_string())
            .filter_map(|d| d["name"].as_str())
            .collect();
        ws.sort_unstable();
        ws.dedup();
        let mut ext: Vec<String> = deps
            .iter()
            .filter(|d| !d["path"].is_string())
            .filter_map(|d| {
                let n = d["name"].as_str()?;
                Some(match d["kind"].as_str() {
                    Some(k) => format!("{n} ({k})"),
                    None => n.to_string(),
                })
            })
            .collect();
        ext.sort();
        ext.dedup();
        for d in &ws {
            edges.push(format!(
                "  {} --> {}",
                name.replace('-', "_"),
                d.replace('-', "_")
            ));
        }
        let or_dash = |v: String| if v.is_empty() { "—".to_string() } else { v };
        let _ = writeln!(
            s,
            "| `{name}` | `{path}` | {class} | {} | {} | {} | {} |",
            ulei["role"].as_str().unwrap_or("").replace('|', "\\|"),
            or_dash(used.join(", ")),
            or_dash(
                ws.iter()
                    .map(|d| format!("`{d}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            or_dash(ext.join(", ")),
        );
    }
    s.push_str("\n## Dependency graph\n\n```mermaid\ngraph LR\n");
    for p in &pkgs {
        let name = p["name"].as_str().unwrap_or("?");
        let _ = writeln!(s, "  {}[\"{name}\"]", name.replace('-', "_"));
    }
    edges.sort();
    for e in edges {
        s.push_str(&e);
        s.push('\n');
    }
    s.push_str("```\n\n## Contracts\n\n| Id | Version | Status | Kind | File | Title | Used by |\n|---|---|---|---|---|---|---|\n");
    for c in &contracts {
        let users: Vec<String> = pkgs
            .iter()
            .filter(|p| {
                p["metadata"]["ulei"]["contracts"]
                    .as_array()
                    .is_some_and(|a| a.iter().any(|x| x.as_str() == Some(&c.id)))
            })
            .filter_map(|p| p["name"].as_str().map(|n| format!("`{n}`")))
            .collect();
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | `contracts/{}` | {} | {} |",
            c.id,
            c.version,
            c.status,
            c.kind,
            c.file,
            c.title,
            if users.is_empty() {
                "—".into()
            } else {
                users.join(", ")
            }
        );
    }
    s.push_str("\n## Class-1 products (ecosystem.lock)\n\n| Product | Repository | Version | Pin | Contract |\n|---|---|---|---|---|\n");
    if let Some(products) = lock.get("products").and_then(|p| p.as_table()) {
        for (name, p) in products {
            let get = |k: &str| p.get(k).and_then(|v| v.as_str()).unwrap_or("—").to_string();
            let commit = get("commit");
            let short = commit.get(..12).unwrap_or(&commit);
            let _ = writeln!(
                s,
                "| {name} | {} | {} | `{short}` | {} |",
                get("repo"),
                get("version"),
                get("contract")
            );
        }
    }
    Ok(s)
}
