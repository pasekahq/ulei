//! Generates Rust wire types from `contracts/` into `crates/contracts/src/generated/` and the
//! fixture test `crates/contracts/tests/fixtures.rs`.
//!
//! Supported schema subset (anything else is a generation error, keep contracts simple):
//! objects with `properties`/`required`/`additionalProperties: false`, free-form objects,
//! string enums, string/integer/number/boolean, arrays, a required `[<type>, "null"]`
//! property, `$ref` to named definitions or to `#` (the typed document root).
//! A struct denies unknown fields exactly where its schema says `additionalProperties: false`.
//! Validation keywords (`pattern`, ranges, lengths) are not encoded in the types; producers
//! and consumers enforce them, and fixtures are checked against the full schema.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

use serde_json::Value;

use crate::contracts::{self, Contract};
use crate::util::{self, Errors, Res};

const HEADER: &str = "// @generated by `cargo xtask gen-contracts` from contracts/. Do not edit.";

pub fn run(root: &Path, check: bool) -> Res {
    let contracts = contracts::load(root).map_err(|e| vec![e])?;
    let mut errors = Errors::new();
    let gen_dir = root.join("crates/contracts/src/generated");
    let mut files: Vec<(std::path::PathBuf, String)> = Vec::new();
    for c in &contracts {
        match module(c) {
            Ok(code) => files.push((gen_dir.join(format!("{}.rs", c.module())), code)),
            Err(e) => errors.push(format!("{}: {e}", c.id)),
        }
    }
    files.push((gen_dir.join("mod.rs"), mod_rs(&contracts)));
    match fixtures_test(root, &contracts) {
        Ok(code) => files.push((root.join("crates/contracts/tests/fixtures.rs"), code)),
        Err(e) => errors.push(e),
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    for (path, code) in files {
        match rustfmt(&code) {
            Ok(formatted) => util::write_or_check(root, &path, &formatted, check, &mut errors),
            Err(e) => errors.push(format!("{}: {e}", util::rel(root, &path))),
        }
    }
    if check {
        // A stale file that is no longer generated is also drift.
        for f in util::files_with_ext(&gen_dir, "rs") {
            let name = f.file_stem().and_then(|s| s.to_str()).unwrap_or("");
            if name != "mod" && !contracts.iter().any(|c| c.module() == name) {
                errors.push(format!(
                    "{} is not generated from any contract",
                    util::rel(root, &f)
                ));
            }
        }
    }
    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors)
    }
}

fn rustfmt(code: &str) -> Result<String, String> {
    let rustfmt = std::env::var("RUSTFMT").unwrap_or_else(|_| "rustfmt".into());
    let mut child = Command::new(rustfmt)
        .args(["--edition", "2024"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt: no stdin")?
        .write_all(code.as_bytes())
        .map_err(|e| format!("rustfmt: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    String::from_utf8(out.stdout).map_err(|e| e.to_string())
}

fn pascal(s: &str) -> String {
    let mut out = String::new();
    for part in s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
    {
        let mut ch = part.chars();
        if let Some(f) = ch.next() {
            out.push(f.to_ascii_uppercase());
            out.push_str(ch.as_str());
        }
    }
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    out
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where",
    "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "try",
    "typeof", "unsized", "virtual", "yield",
];

fn field_ident(key: &str) -> Result<String, String> {
    let ok = key
        .chars()
        .next()
        .is_some_and(|c| c.is_ascii_lowercase() || c == '_')
        && key
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if !ok || ["self", "super", "crate"].contains(&key) {
        return Err(format!(
            "property `{key}` is not a snake_case Rust identifier"
        ));
    }
    Ok(if KEYWORDS.contains(&key) {
        format!("r#{key}")
    } else {
        key.to_string()
    })
}

fn doc(out: &mut String, text: &str) {
    for line in text.lines() {
        let _ = writeln!(out, "/// {}", line.trim_end());
    }
}

struct Gen {
    out: String,
    /// Type name of the document root, the target of `$ref: "#"`.
    root: Option<String>,
}

impl Gen {
    /// Returns the Rust type for `schema`, emitting nested items named after `ctx`.
    fn ty(&mut self, schema: &Value, ctx: &str) -> Result<String, String> {
        if let Some(r) = schema["$ref"].as_str() {
            if r == "#" {
                return self
                    .root
                    .clone()
                    .ok_or(format!("{ctx}: `#` has no typed root"));
            }
            return r
                .strip_prefix("#/$defs/")
                .map(str::to_string)
                .ok_or(format!("unsupported $ref `{r}`"));
        }
        if schema.get("enum").is_some() {
            self.item(ctx, schema)?;
            return Ok(ctx.to_string());
        }
        if let Some(types) = schema["type"].as_array() {
            let inner = match types.as_slice() {
                [t, Value::String(n)] | [Value::String(n), t] if n == "null" => t,
                _ => {
                    return Err(format!(
                        "{ctx}: only `[<type>, \"null\"]` type lists are supported"
                    ));
                }
            };
            let mut one = schema.clone();
            one["type"] = inner.clone();
            return Ok(format!("Option<{}>", self.ty(&one, ctx)?));
        }
        match schema["type"].as_str() {
            Some("string") => Ok("String".into()),
            Some("boolean") => Ok("bool".into()),
            Some("number") => Ok("f64".into()),
            Some("integer") => Ok(if schema["minimum"].as_f64().is_some_and(|m| m >= 0.0) {
                "u64".into()
            } else {
                "i64".into()
            }),
            Some("array") => Ok(format!(
                "Vec<{}>",
                self.ty(&schema["items"], &format!("{ctx}Item"))?
            )),
            Some("object") if schema.get("properties").is_some() => {
                self.item(ctx, schema)?;
                Ok(ctx.to_string())
            }
            Some("object") => Ok("serde_json::Map<String, serde_json::Value>".into()),
            None if schema
                .as_object()
                .is_some_and(|o| o.keys().all(|k| k == "description")) =>
            {
                Ok("serde_json::Value".into())
            }
            other => Err(format!("{ctx}: unsupported schema type {other:?}")),
        }
    }

    /// Emits a named item (struct, enum or alias) for `schema`.
    fn item(&mut self, name: &str, schema: &Value) -> Result<(), String> {
        let description = schema["description"].as_str().unwrap_or("Wire type.");
        if let Some(values) = schema["enum"].as_array() {
            let values: Vec<&str> = values
                .iter()
                .map(|v| {
                    v.as_str()
                        .ok_or(format!("{name}: only string enums are supported"))
                })
                .collect::<Result<_, _>>()?;
            let mut s = String::new();
            doc(&mut s, description);
            s.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]\n");
            let _ = writeln!(s, "pub enum {name} {{");
            let mut seen = std::collections::BTreeSet::new();
            for v in &values {
                let variant = pascal(v);
                if !seen.insert(variant.clone()) {
                    return Err(format!(
                        "{name}: enum values collide on variant `{variant}`"
                    ));
                }
                let _ = writeln!(s, "/// `{v}`.\n#[serde(rename = \"{v}\")]\n{variant},");
            }
            s.push_str("}\n\n");
            let _ = writeln!(
                s,
                "impl {name} {{\n/// The wire value.\npub const fn as_str(self) -> &'static str {{\nmatch self {{"
            );
            for v in &values {
                let _ = writeln!(s, "Self::{} => \"{v}\",", pascal(v));
            }
            s.push_str("}\n}\n}\n\n");
            self.out.push_str(&s);
            return Ok(());
        }
        if schema["type"].as_str() == Some("object")
            && let Some(props) = schema["properties"].as_object()
        {
            let required: Vec<&str> = schema["required"]
                .as_array()
                .map(|a| a.iter().filter_map(Value::as_str).collect())
                .unwrap_or_default();
            let mut fields = String::new();
            for (key, prop) in props {
                let ident = field_ident(key)?;
                let ty = self.ty(prop, &format!("{name}{}", pascal(key)))?;
                let fallback = prop["$ref"]
                    .as_str()
                    .and_then(|r| r.rsplit('/').next())
                    .map_or_else(|| "Field.".to_string(), |t| format!("See [`{t}`]."));
                doc(
                    &mut fields,
                    prop["description"].as_str().unwrap_or(&fallback),
                );
                if required.contains(&key.as_str()) {
                    let _ = writeln!(fields, "pub {ident}: {ty},");
                } else if ty.starts_with("Option<") {
                    return Err(format!(
                        "{name}.{key}: an optional nullable property is not supported"
                    ));
                } else {
                    let _ = writeln!(
                        fields,
                        "#[serde(default, skip_serializing_if = \"Option::is_none\")]\npub {ident}: Option<{ty}>,"
                    );
                }
            }
            let mut s = String::new();
            doc(&mut s, description);
            s.push_str(
                "#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n",
            );
            if schema["additionalProperties"] == Value::Bool(false) {
                s.push_str("#[serde(deny_unknown_fields)]\n");
            }
            let _ = writeln!(s, "pub struct {name} {{\n{fields}}}\n");
            self.out.push_str(&s);
            return Ok(());
        }
        let ty = self.ty(schema, &format!("{name}Inner"))?;
        let mut s = String::new();
        doc(&mut s, description);
        let _ = writeln!(s, "pub type {name} = {ty};\n");
        self.out.push_str(&s);
        Ok(())
    }
}

fn module(c: &Contract) -> Result<String, String> {
    let root = c.root();
    let mut g = Gen {
        out: String::new(),
        root: root.as_ref().map(|(name, _)| name.clone()),
    };
    if let Some((name, schema)) = root {
        g.item(&name, &schema)?;
    }
    for (name, schema) in c.defs() {
        g.item(&name, &schema)?;
    }
    let mut s = format!("{HEADER}\n\n");
    let _ = writeln!(
        s,
        "//! {} {} ({}): {}. Source: `contracts/{}`.\n",
        c.id, c.version, c.status, c.title, c.file
    );
    s.push_str("#![allow(clippy::doc_markdown, clippy::struct_excessive_bools)]\n\n");
    s.push_str(&g.out);
    Ok(s)
}

fn mod_rs(contracts: &[Contract]) -> String {
    let mut s = format!("{HEADER}\n\n//! Generated wire types, one module per contract.\n\n");
    for c in contracts {
        let _ = writeln!(s, "pub mod {};", c.module());
    }
    s.push_str(
        "\n/// A contract compiled into this build.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct Contract {\n/// Contract id, e.g. `C1`.\npub id: &'static str,\n/// Semantic version of the schema.\npub version: &'static str,\n/// File under `contracts/`.\npub file: &'static str,\n/// Title.\npub title: &'static str,\n/// `stable`, `draft` or `vendored`.\npub status: &'static str,\n}\n\n/// All contracts, in id order.\npub const CONTRACTS: &[Contract] = &[\n",
    );
    for c in contracts {
        let _ = writeln!(
            s,
            "Contract {{ id: {:?}, version: {:?}, file: {:?}, title: {:?}, status: {:?} }},",
            c.id, c.version, c.file, c.title, c.status
        );
    }
    s.push_str("];\n");
    s
}

